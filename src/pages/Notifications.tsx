import { useState } from 'react';
import { useNavigate } from 'react-router-dom';
import * as S from '../store/store';
import { Button, Card, Empty, PageHeader, Tabs, cx } from '../ui/kit';
import { fmtDateTime } from '../domain/util';

export default function Notifications() {
  const db = S.useDB();
  const me = S.useMe()!;
  const nav = useNavigate();
  const [tab, setTab] = useState<'unread' | 'all'>('unread');
  const all = S.notificationsFor(db, me);
  const unread = all.filter((n) => !n.readBy.includes(me.id));
  const list = (tab === 'unread' ? unread : all).slice(0, 300);
  const wa = (phone: string, body: string) => `https://wa.me/91${phone}?text=${encodeURIComponent(body)}`;
  return (
    <>
      <PageHeader title="Notifications" sub="Generated by the automation engine. Rules are configured in Settings → Automation."
        actions={unread.length > 0 && <Button onClick={() => S.markRead(unread.map((n) => n.id))}>Mark all read</Button>} />
      <Tabs value={tab} onChange={setTab} tabs={[{ id: 'unread', label: 'Unread', count: unread.length }, { id: 'all', label: 'All', count: all.length }]} />
      <Card>
        {!list.length ? <Empty title={tab === 'unread' ? "You're all caught up" : 'No notifications yet'} /> : (
          <div className="divide-y divide-line">
            {list.map((n) => {
              const isUnread = !n.readBy.includes(me.id);
              return (
                <div key={n.id} className={cx('flex gap-3 px-4 py-3', isUnread && 'bg-accent-soft/40')}>
                  <span className={cx('mt-1.5 size-2 rounded-full shrink-0', isUnread ? 'bg-accent' : 'bg-transparent')} />
                  <button className="flex-1 text-left" onClick={() => { S.markRead([n.id]); nav(n.link); }}>
                    <div className="font-medium">{n.title}</div>
                    <div className="text-zinc-600">{n.body}</div>
                    <div className="text-xs text-muted mt-0.5">{fmtDateTime(n.at)}</div>
                  </button>
                  {n.phone && (
                    // ponytail: hands off to WhatsApp for a human to send; approved-provider API (Gupshup/Interakt/MSG91) comes with the backend.
                    <a href={wa(n.phone, `Hello, this is a reminder from ${db.settings.academyName}: ${n.body.split(' — ')[1] ?? n.body}. Please ignore if already paid.`)} target="_blank" rel="noreferrer" className="self-center text-xs text-accent whitespace-nowrap">WhatsApp</a>
                  )}
                </div>
              );
            })}
          </div>
        )}
      </Card>
    </>
  );
}
