import { useEffect, useState } from 'react';
import { useNavigate } from 'react-router-dom';
import * as S from '../store/store';
import { Badge, Button, Card, Empty, PageHeader, Select, Tabs, cx } from '../ui/kit';
import { cloudEnabled, sb } from '../store/cloud';
import { fmtDate, fmtDateTime, fmtTime } from '../domain/util';

export default function Notifications() {
  const db = S.useDB();
  const me = S.useMe()!;
  const nav = useNavigate();
  const [tab, setTab] = useState<'unread' | 'all' | 'reminders'>('unread');
  const all = S.notificationsFor(db, me);
  const unread = all.filter((n) => !n.readBy.includes(me.id));
  const list = (tab === 'unread' ? unread : all).slice(0, 300);
  const wa = (phone: string, body: string) => `https://wa.me/91${phone}?text=${encodeURIComponent(body)}`;
  return (
    <>
      <PageHeader title="Notifications" sub="Generated by the automation engine. Rules are configured in Settings → Automation."
        actions={unread.length > 0 && <Button onClick={() => S.markRead(unread.map((n) => n.id))}>Mark all read</Button>} />
      <Tabs value={tab} onChange={setTab} tabs={[{ id: 'unread', label: 'Unread', count: unread.length }, { id: 'all', label: 'All', count: all.length }, ...(cloudEnabled && S.allowed('batches', 'view', db) ? [{ id: 'reminders' as const, label: 'Class reminders' }] : [])]} />
      {tab === 'reminders' ? <ClassReminders /> : <Card>
        {!list.length ? <Empty title={tab === 'unread' ? "You're all caught up" : 'No notifications yet'} /> : (
          <div className="divide-y divide-line">
            {list.map((n) => {
              const isUnread = !n.readBy.includes(me.id);
              return (
                <div key={n.id} className={cx('flex gap-3 px-4 py-3', isUnread && 'bg-accent-soft/40')}>
                  <span className={cx('mt-1.5 size-2 rounded-full shrink-0', isUnread ? 'bg-accent' : 'bg-transparent')} />
                  <button className="flex-1 text-left" onClick={() => { S.markRead([n.id]); nav(n.link); }}>
                    <div className="font-medium">{n.title}</div>
                    <div className="text-zinc-600">{n.body}</div>
                    <div className="text-xs text-muted mt-0.5">{fmtDateTime(n.at)}</div>
                  </button>
                  {n.phone && (
                    // ponytail: hands off to WhatsApp for a human to send; approved-provider API (Gupshup/Interakt/MSG91) comes with the backend.
                    <a href={wa(n.phone, `Hello, this is a reminder from ${db.settings.academyName}: ${n.body.split(' — ')[1] ?? n.body}. Please ignore if already paid.`)} target="_blank" rel="noreferrer" className="self-center text-xs text-accent whitespace-nowrap">WhatsApp</a>
                  )}
                </div>
              );
            })}
          </div>
        )}
      </Card>}
    </>
  );
}

type JobRow = { id: number; kind: string; status: string; send_at: string; sent_at: string | null; error: string | null; class_id: string | null; student_id: string };
const KIND: Record<string, string> = { day_before: '1 day before', morning: 'Morning of class', soon: '30 min before', test: 'Test' };
const STATUS_TONE: Record<string, string> = { sent: 'green', pending: 'blue', sending: 'blue', failed: 'red', no_device: 'gray', expired: 'gray' };
/** Push reminders planned for scheduled classes: totals, and the delivery history (read from the server). */
function ClassReminders() {
  const db = S.useDB();
  const [rows, setRows] = useState<JobRow[] | null>(null);
  const [err, setErr] = useState('');
  const [filter, setFilter] = useState('');
  const load = () => { setErr(''); void sb!.from('notification_jobs').select('id,kind,status,send_at,sent_at,error,class_id,student_id').order('send_at', { ascending: false }).limit(1000)
    .then(({ data, error }) => { if (error) setErr(error.message); else setRows((data ?? []) as JobRow[]); }); };
  useEffect(load, []);
  if (err) return <Card><Empty title="Couldn't load reminders" body={err} action={<Button onClick={load}>Try again</Button>} /></Card>;
  if (!rows) return <Card><p className="text-center text-muted py-10">Loading…</p></Card>;
  const n = (st: string) => rows.filter((r) => r.status === st).length;
  const cls = (id: string | null) => db.classes.find((c) => c.id === id);
  const shown = rows.filter((r) => !filter || r.status === filter);
  return (
    <div className="space-y-4">
      <div className="grid grid-cols-2 sm:grid-cols-5 gap-3">
        {([['Total', rows.length, ''], ['Sent', n('sent'), 'text-emerald-600'], ['Pending', n('pending') + n('sending'), 'text-navy'], ['Failed', n('failed'), 'text-red-600'], ['No device', n('no_device'), 'text-zinc-500']] as const).map(([l, v, t]) => (
          <div key={l} className="rounded-xl border border-line bg-white px-4 py-3"><div className="text-[11px] font-semibold uppercase tracking-wider text-muted">{l}</div><div className={cx('text-[24px] font-bold tabular', t || 'text-ink')}>{v}</div></div>
        ))}
      </div>
      <p className="text-[12.5px] text-muted">"No device" means the student has not turned on reminders yet (they do it from their student login). Reminders are sent by the server every minute.</p>
      <Card>
        <div className="flex items-center gap-2 px-4 py-3 border-b border-line">
          <span className="font-semibold text-navy mr-auto">Delivery history</span>
          <Select value={filter} onChange={(e) => setFilter(e.target.value)} className="w-40" options={[{ value: '', label: 'All' }, ...['sent', 'pending', 'failed', 'no_device', 'expired'].map((v) => ({ value: v, label: v.replace('_', ' ') }))]} />
          <Button size="sm" onClick={load}>Refresh</Button>
        </div>
        {!shown.length ? <Empty title="No reminders yet" body="They are created automatically when you schedule a class for a batch." /> : (
          <div className="divide-y divide-line">
            {shown.slice(0, 300).map((r) => { const c = cls(r.class_id), st = db.students.find((x) => x.id === r.student_id); return (
              <div key={r.id} className="flex flex-wrap items-center gap-x-3 gap-y-1 px-4 py-2.5 text-[13px]">
                <div className="min-w-0 flex-1"><div className="font-medium">{st?.name ?? 'Student'} <span className="text-muted font-normal">{st?.code}</span></div>
                  <div className="text-[12px] text-muted">{c ? `${db.batches.find((b) => b.id === c.batchId)?.name} · ${fmtDate(c.date)} ${fmtTime(c.startTime)}` : 'Test message'} · {KIND[r.kind] ?? r.kind}</div></div>
                <div className="text-right text-[12px] text-zinc-600 tabular">{r.sent_at ? `Sent ${fmtDateTime(r.sent_at)}` : `Due ${fmtDateTime(r.send_at)}`}{r.error && r.status !== 'sent' ? <div className="text-red-600 max-w-64 truncate" title={r.error}>{r.error}</div> : null}</div>
                <Badge tone={STATUS_TONE[r.status] ?? 'gray'}>{r.status.replace('_', ' ')}</Badge>
              </div>
            ); })}
          </div>
        )}
      </Card>
    </div>
  );
}
